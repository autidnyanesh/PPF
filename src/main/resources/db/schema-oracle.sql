-- Optional Oracle bootstrap for PPF. The app also creates tables with ddl-auto=update.
CREATE SEQUENCE PPF_ACCOUNTS_SEQ START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE PPF_TRANSACTIONS_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE PPF_ACCOUNTS (
  ID NUMBER(19) PRIMARY KEY,
  ACCOUNT_NUMBER VARCHAR2(30) NOT NULL UNIQUE,
  CUSTOMER_NAME VARCHAR2(160) NOT NULL,
  CUSTOMER_ID VARCHAR2(50),
  BALANCE NUMBER(18,2) NOT NULL,
  STATUS VARCHAR2(20) NOT NULL,
  OPENED_ON DATE NOT NULL,
  VERSION_NUMBER NUMBER(19) DEFAULT 0 NOT NULL
);

CREATE TABLE PPF_TRANSACTIONS (
  ID NUMBER(19) PRIMARY KEY,
  ACCOUNT_ID NUMBER(19) NOT NULL REFERENCES PPF_ACCOUNTS(ID),
  TRANSACTION_TYPE VARCHAR2(20) NOT NULL,
  AMOUNT NUMBER(18,2) NOT NULL,
  REMARKS VARCHAR2(300),
  CREATED_AT TIMESTAMP NOT NULL
);
